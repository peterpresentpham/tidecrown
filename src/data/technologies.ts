export type Technology = {
  id: TechnologyId;
  code: string;
  name: string;
  branch: Branch;
  tier: number;
  requires: TechnologyId[];
  cost: Resource;
  turns: number;
  effect: string;
};
export const TECHNOLOGIES = Object.fromEntries(
  rows.map(([id, code, name, branch, tier, requires, effect]) => [
    id,
    {
      id,
      code,
      name,
      branch,
      tier,
      requires: [...requires],
      cost: {
        gold: BALANCE.technologyGold[tier],
        food: 0,
        wood: tier >= 3 && ['siege', 'naval'].includes(branch) ? BALANCE.advancedResearchWood : 0,
        stone: tier === 4 && branch === 'siege' ? 5 : 0,
      },
      turns: tier === 1 ? 1 : tier === 4 ? 3 : 2,
      effect,
    },
  ])
) as Record<TechnologyId, Technology>;
